defmodule SdrAgent.AI.ModelProviderInventoryTest do
  @moduledoc """
  A source regression inventory of the model-call paths in `lib/`: it
  parses every `lib/**/*.ex` file and checks who calls what. Two
  inventories share one walker.

  **R0-04-5** (`docs/product/r0/r0-04-seam.md`): every `prepare/2` and
  `complete/2` call on a model provider in `lib/` goes through the
  `ModelProvider` facade, apart from three exceptions named exactly.
  Characterization of main; its sensitivity was shown with temporary
  local edits, which were then reverted.

  It flags:
  - a remote call with two arguments on a module that implements
    `SdrAgent.AI.ModelProvider`. The module may be fully qualified or
    aliased: a plain `alias`, `alias ..., as:`, or a grouped
    `alias A.{B, C}`, each scoped to the module or function body it is
    written in;
  - a remote call on a dynamic receiver (`var.prepare(_, _)` or
    `var.complete(_, _)`);
  - a capture (`&Mod.prepare/2`, `&Mod.complete/2`);
  - `apply/3` or `Kernel.apply/3` with a literal `:prepare` or
    `:complete` and two arguments, or an argument list computed at
    runtime.

  A provider module's own internals are exempt only for calls to its own
  module.

  **L2-E3 caller inventory** (`notes/features/l2-e3-ordinary-calls.org`,
  section 4): each entry point below is allowed only from the callers
  named, by caller module and function, in `@entry_point_callers`, and
  every named caller must still be found:
  - the ClaudeCLI server message: `GenServer.call/2,3` (or
    `:gen_server.call/2,3`) whose message is a three-element tuple
    literal starting with `:complete` (`{:complete, request,
    enqueued_at}`) — only `ClaudeCLI.complete/2`;
  - `SdrAgent.Agents.admit_launch/3` — only `ClaudeCLI.admit/3`;
  - `SdrAgent.Agents.reserve_model_invocation/3` — only the facade's
    `reserve/2` and the test-seam `CalibrationConsole.Calibrate.reserve/1`;
  - `SdrAgent.SDR.Model.call/4` — only `perform/2` of the four SDR
    actions `ScoreLead`, `ClassifyReply`, `DraftEmail` and
    `BuildEvidenceBundle`;
  - `SdrAgent.AI.ModelProvider.calibration_call/3` — only
    `CalibrationConsole.Calibrate.call/3`.

  Each is flagged in the same forms as above: a remote call, fully
  qualified or through any of those alias forms; a capture
  `&Mod.fun/arity`; `apply/3` or `Kernel.apply/3` with a literal function
  name. A dynamic receiver (a variable or module attribute) with the same
  function name and arity is flagged too, and an argument list computed
  at runtime counts as every arity (and, for `:call` on a server, as the
  server message).

  **Its limits:** this is a regression inventory of source, not runtime
  caller authorization: it stops nothing at runtime, and it scans code
  that a build compiles out (the test-seam modules) like any other.
  Not seen: a function name computed at runtime (`apply(m, f, args)`); a
  GenServer message built at runtime or held in a variable
  (`GenServer.call(server, message)`); a capture of `GenServer.call/2,3`,
  whose message is not in the source; a call through any other process
  API (`:gen.call/4`, `send/2`); a local, unqualified call inside the
  defining module; code generated by macros; and anything outside
  `lib/**/*.ex`.
  """
  use ExUnit.Case, async: true

  @behaviour_module SdrAgent.AI.ModelProvider
  @names [:prepare, :complete]
  @root Path.expand("../../../lib", __DIR__)

  # {caller module, caller function, receiver, called function}
  @exceptions MapSet.new([
                {SdrAgent.AI.ModelProvider, :prepare, :dynamic, :prepare},
                {SdrAgent.AI.ModelProvider, :provider_call, :dynamic, :complete},
                {SdrAgent.AI.ModelProvider.CalibrationCall, :target,
                 SdrAgent.AI.ModelProvider.ClaudeCLI, :prepare},
                {SdrAgent.AI.ModelProvider.Runtime, :prepared, :dynamic, :prepare}
              ])

  @claude_cli SdrAgent.AI.ModelProvider.ClaudeCLI
  @calibrate SdrAgent.CalibrationConsole.Calibrate

  # {receiver module, function} => arity of each L2-E3 entry point.
  @entry_points %{
    {SdrAgent.Agents, :admit_launch} => 3,
    {SdrAgent.Agents, :reserve_model_invocation} => 3,
    {SdrAgent.SDR.Model, :call} => 4,
    {SdrAgent.AI.ModelProvider, :calibration_call} => 3
  }
  @entry_names Enum.uniq([:call | for({{_module, name}, _arity} <- @entry_points, do: name)])
  @servers [GenServer, :gen_server]
  # The called-function slot of a key for the ClaudeCLI server message.
  @server_message {:call, :complete}

  # {caller module, caller function, receiver, called function}
  @entry_point_callers MapSet.new([
                         {@claude_cli, :complete, GenServer, @server_message},
                         {@claude_cli, :admit, SdrAgent.Agents, :admit_launch},
                         {SdrAgent.AI.ModelProvider, :reserve, SdrAgent.Agents,
                          :reserve_model_invocation},
                         {@calibrate, :reserve, SdrAgent.Agents, :reserve_model_invocation},
                         {SdrAgent.SDR.Actions.ScoreLead, :perform, SdrAgent.SDR.Model, :call},
                         {SdrAgent.SDR.Actions.ClassifyReply, :perform, SdrAgent.SDR.Model,
                          :call},
                         {SdrAgent.SDR.Actions.DraftEmail, :perform, SdrAgent.SDR.Model, :call},
                         {SdrAgent.SDR.Actions.BuildEvidenceBundle, :perform, SdrAgent.SDR.Model,
                          :call},
                         {@calibrate, :call, SdrAgent.AI.ModelProvider, :calibration_call}
                       ])

  test "every provider prepare/complete call goes through the facade or a named exception" do
    calls = inventory(@root, &scan/2)
    unexpected = Enum.reject(calls, &MapSet.member?(@exceptions, Map.fetch!(&1, :key)))

    assert unexpected == [],
           "provider calls outside the facade:\n" <>
             Enum.map_join(unexpected, "\n", &"  #{&1.file}:#{&1.line} #{inspect(&1.key)}")

    found = MapSet.new(calls, & &1.key)

    for exception <- @exceptions do
      assert exception in found, "named exception not found any more: #{inspect(exception)}"
    end
  end

  test "each enforced form is detected (synthetic sources, no lib edits)" do
    sources = %{
      "direct" => """
      defmodule Probe.Direct do
        alias SdrAgent.AI.ModelProvider.ClaudeCLI
        def go(r), do: ClaudeCLI.complete(r, [])
      end
      """,
      "qualified" => """
      defmodule Probe.Qualified do
        def go(r), do: SdrAgent.AI.ModelProvider.Fake.prepare(r, [])
      end
      """,
      "dynamic" => """
      defmodule Probe.Dynamic do
        def go(mod, r), do: mod.complete(r, [])
      end
      """,
      "grouped_alias" => """
      defmodule Probe.Grouped do
        alias SdrAgent.AI.ModelProvider.{ClaudeCLI, Fake}
        def go(r), do: ClaudeCLI.complete(r, [])
      end
      """,
      "function_scoped_alias" => """
      defmodule Probe.FunctionScoped do
        def go(r) do
          alias SdrAgent.AI.ModelProvider.Fake
          Fake.prepare(r, [])
        end
      end
      """,
      "capture" => """
      defmodule Probe.Capture do
        def go, do: &SdrAgent.AI.ModelProvider.Fake.complete/2
      end
      """,
      "apply" => """
      defmodule Probe.Apply do
        def go(m, r), do: apply(m, :prepare, [r, []])
      end
      """,
      "kernel_apply" => """
      defmodule Probe.KernelApply do
        def go(m, r), do: Kernel.apply(m, :complete, [r, []])
      end
      """
    }

    for {name, source} <- sources do
      assert [_] = scan(source, name), "#{name} was not detected"
    end

    other = """
    defmodule Probe.Other do
      def go(changeset), do: Map.get(changeset, :complete) || Task.yield(changeset, 1)
    end
    """

    assert scan(other, "other") == []

    # An alias made inside one function does not reach the next one: there
    # `Fake` is the unaliased module `Fake`, not a provider.
    scoped = """
    defmodule Probe.Scope do
      def a(r) do
        alias SdrAgent.AI.ModelProvider.Fake
        Fake.prepare(r, [])
      end

      def b(r), do: Fake.prepare(r, [])
    end
    """

    assert [%{key: {Probe.Scope, :a, SdrAgent.AI.ModelProvider.Fake, :prepare}}] =
             scan(scoped, "scope")
  end

  test "each entry point is called only from its named callers" do
    entries = inventory(@root, &scan_entries/2)
    unexpected = unexpected_entries(entries)

    assert unexpected == [],
           "entry-point calls outside their named callers:\n" <>
             Enum.map_join(unexpected, "\n", &"  #{&1.file}:#{&1.line} #{inspect(&1.key)}")

    found = MapSet.new(entries, & &1.key)

    for caller <- @entry_point_callers do
      assert caller in found, "named caller not found any more: #{inspect(caller)}"
    end
  end

  test "each enforced entry-point form is detected (synthetic sources, no lib edits)" do
    probes =
      Enum.flat_map(@entry_points, &entry_probes/1) ++
        Enum.map(server_probes(), fn {label, receiver, body} ->
          {"server_#{label}", receiver, @server_message, body}
        end)

    for {label, receiver, called, body} <- probes do
      probe = Module.concat(Probe, Macro.camelize(label))
      source = "defmodule #{inspect(probe)} do\n  #{body}\nend\n"

      assert [%{key: key}] = scan_entries(source, label), "#{label} was not detected"
      assert key == {probe, :go, receiver, called}
      assert unexpected_entries([%{key: key}]) != [], "#{label} was not flagged"
    end
  end

  test "each named caller is not flagged, and the same call elsewhere is (synthetic sources)" do
    for {caller, function, receiver, called} = key <- @entry_point_callers do
      entries = scan_entries(entry_source(caller, function, receiver, called), "named")
      assert [%{key: ^key}] = entries
      assert unexpected_entries(entries) == [], "named caller was flagged: #{inspect(key)}"

      # The named module from another function, and the named function
      # from another module.
      for {other_module, other_function} <- [{caller, :elsewhere}, {Probe.Elsewhere, function}] do
        source = entry_source(other_module, other_function, receiver, called)
        other = {other_module, other_function, receiver, called}

        assert [%{key: ^other}] = unexpected_entries(scan_entries(source, "elsewhere")),
               "#{inspect(other)} was not flagged"
      end
    end
  end

  test "near misses and the stated limits are not entry points (synthetic sources)" do
    bodies = %{
      "two_element_message" => "GenServer.call(s, {:complete, r})",
      "other_message" => "GenServer.call(s, {:status, r, t}, :infinity)",
      "cast" => "GenServer.cast(s, {:complete, r, t})",
      "runtime_message" => "GenServer.call(s, message)",
      "server_capture" => "&GenServer.call/2",
      "other_receiver" =>
        "alias SdrAgent.Agents.Admission.Gate\n    Gate.admit_launch(run, invocation, store)",
      "wrong_arity" => "SdrAgent.Agents.admit_launch(a1, a2)",
      "model_call_arity_3" => "SdrAgent.SDR.Model.call(a1, a2, a3)",
      "other_call_arity_4" => "SdrAgent.Other.call(a1, a2, a3, a4)",
      "runtime_name" => "apply(SdrAgent.Agents, name, [a1, a2, a3])",
      "local" => "admit_launch(a1, a2, a3)"
    }

    for {label, body} <- bodies do
      source = "defmodule Probe.NearMiss do\n  def go do\n    #{body}\n  end\nend\n"
      assert scan_entries(source, label) == [], "#{label} was flagged"
    end

    # An alias made inside one function does not reach the next one.
    scoped = """
    defmodule Probe.EntryScope do
      def a do
        alias SdrAgent.Agents
        Agents.admit_launch(a1, a2, a3)
      end

      def b, do: Agents.admit_launch(a1, a2, a3)
    end
    """

    assert [%{key: {Probe.EntryScope, :a, SdrAgent.Agents, :admit_launch}}] =
             scan_entries(scoped, "scope")
  end

  ## Synthetic entry-point sources

  # {label, expected receiver, called function, module body}
  defp entry_probes({{module, name}, arity}) do
    mod = inspect(module)
    [last | rest] = module |> Module.split() |> Enum.reverse()
    base = rest |> Enum.reverse() |> Enum.join(".")
    args = arguments(arity)
    call = "#{name}(#{args})"

    [
      {"qualified", module, "def go, do: #{mod}.#{call}"},
      {"alias", module, "alias #{mod}\n  def go, do: #{last}.#{call}"},
      {"alias_as", module, "alias #{mod}, as: Target\n  def go, do: Target.#{call}"},
      {"grouped_alias", module, "alias #{base}.{Other, #{last}}\n  def go, do: #{last}.#{call}"},
      {"function_scoped_alias", module,
       "def go do\n    alias #{mod}\n    #{last}.#{call}\n  end"},
      {"capture", module, "def go, do: &#{mod}.#{name}/#{arity}"},
      {"apply", module, "def go, do: apply(#{mod}, :#{name}, [#{args}])"},
      {"kernel_apply", module, "def go, do: Kernel.apply(#{mod}, :#{name}, [#{args}])"},
      {"apply_computed_args", module, "def go(args), do: apply(#{mod}, :#{name}, args)"},
      {"dynamic", :dynamic, "def go(m), do: m.#{call}"},
      {"dynamic_capture", :dynamic, "def go(m), do: &m.#{name}/#{arity}"},
      {"dynamic_apply", :dynamic, "def go(m), do: apply(m, :#{name}, [#{args}])"}
    ]
    |> Enum.map(fn {label, receiver, body} -> {"#{name}_#{label}", receiver, name, body} end)
  end

  # {label, expected receiver, module body} for the ClaudeCLI server message.
  defp server_probes do
    message = "{:complete, r, System.monotonic_time(:millisecond)}"

    [
      {"qualified", GenServer, "def go(s, r), do: GenServer.call(s, #{message})"},
      {"with_timeout", GenServer, "def go(s, r), do: GenServer.call(s, #{message}, :infinity)"},
      {"alias_as", GenServer,
       "alias GenServer, as: Server\n  def go(s, r), do: Server.call(s, #{message})"},
      {"function_scoped_alias", GenServer,
       "def go(s, r) do\n    alias GenServer, as: Server\n    Server.call(s, #{message})\n  end"},
      {"erlang", :gen_server, "def go(s, r), do: :gen_server.call(s, #{message}, 5_000)"},
      {"apply", GenServer, "def go(s, r), do: apply(GenServer, :call, [s, #{message}])"},
      {"kernel_apply", GenServer,
       "def go(s, r), do: Kernel.apply(GenServer, :call, [s, #{message}, :infinity])"},
      {"apply_computed_args", GenServer, "def go(args), do: apply(GenServer, :call, args)"},
      {"dynamic", :dynamic, "def go(m, s, r), do: m.call(s, #{message})"}
    ]
  end

  defp entry_source(module, function, receiver, called) do
    "defmodule #{inspect(module)} do\n  def #{function}(s, r) do\n    " <>
      entry_call(receiver, called) <> "\n  end\nend\n"
  end

  defp entry_call(receiver, @server_message),
    do: "#{inspect(receiver)}.call(s, {:complete, r, enqueued_at}, :infinity)"

  defp entry_call(receiver, name),
    do: "#{inspect(receiver)}.#{name}(#{arguments(Map.fetch!(@entry_points, {receiver, name}))})"

  defp arguments(arity), do: Enum.map_join(1..arity, ", ", &"a#{&1}")

  defp unexpected_entries(entries),
    do: Enum.reject(entries, &MapSet.member?(@entry_point_callers, &1.key))

  ## Inventory

  defp inventory(root, scanner) do
    root
    |> Path.join("**/*.ex")
    |> Path.wildcard()
    |> Enum.flat_map(fn path -> scanner.(File.read!(path), Path.relative_to(path, root)) end)
  end

  defp scan(source, file), do: walk(source, file).calls
  defp scan_entries(source, file), do: walk(source, file).entries

  defp walk(source, file) do
    {:ok, ast} = Code.string_to_quoted(source, columns: true)
    acc = %{stack: [], aliases: %{}, calls: [], entries: []}
    {_ast, acc} = Macro.traverse(ast, acc, &pre/2, &post/2)
    tag = &Map.put(&1, :file, file)
    %{calls: Enum.map(acc.calls, tag), entries: Enum.map(acc.entries, tag)}
  end

  # Each module and function body opens a lexical scope: aliases made in
  # it are dropped when it ends (the alias map is saved on the stack).
  defp pre({:defmodule, _, [{:__aliases__, _, parts} | _]} = node, acc) do
    module = Module.concat(parts)
    {node, %{acc | stack: [{:module, module, acc.aliases} | acc.stack]}}
  end

  defp pre({kind, _, [{name, _, _} | _]} = node, acc)
       when kind in [:def, :defp] and is_atom(name) do
    {node, %{acc | stack: [{:function, name, acc.aliases} | acc.stack]}}
  end

  # Grouped alias: `alias A.B.{C, D.E}` aliases `C` and `E`.
  defp pre({:alias, _, [{{:., _, [{:__aliases__, _, base}, :{}]}, _, children} | _]} = node, acc) do
    aliases =
      Enum.reduce(children, acc.aliases, fn
        {:__aliases__, _, parts}, aliases ->
          Map.put(aliases, List.last(parts), Module.concat(base ++ parts))

        _other, aliases ->
          aliases
      end)

    {node, %{acc | aliases: aliases}}
  end

  defp pre({:alias, _, [{:__aliases__, _, parts} | rest]} = node, acc) do
    target = Module.concat(parts)

    as =
      case rest do
        [[as: {:__aliases__, _, [as]}]] -> as
        _ -> List.last(parts)
      end

    {node, %{acc | aliases: Map.put(acc.aliases, as, target)}}
  end

  defp pre({{:., _, [receiver, name]}, meta, args} = node, acc)
       when name in @names and is_list(args) and length(args) == 2 do
    {node, record(acc, receiver(receiver, acc), name, meta)}
  end

  defp pre({:&, meta, [{:/, _, [{{:., _, [receiver, name]}, _, []}, 2]}]} = node, acc)
       when name in @names do
    {node, record(acc, receiver(receiver, acc), name, meta)}
  end

  defp pre({:apply, meta, [_m, name, args]} = node, acc) when name in @names do
    {node, if(two_args?(args), do: record(acc, :dynamic, name, meta), else: acc)}
  end

  defp pre({{:., _, [{:__aliases__, _, [:Kernel]}, :apply]}, meta, [_m, name, args]} = node, acc)
       when name in @names do
    {node, if(two_args?(args), do: record(acc, :dynamic, name, meta), else: acc)}
  end

  # L2-E3 entry points and the ClaudeCLI server message.
  defp pre({{:., _, [receiver, name]}, meta, args} = node, acc)
       when name in @entry_names and is_list(args) do
    {node, entry(acc, receiver(receiver, acc), name, args, meta)}
  end

  defp pre({:&, meta, [{:/, _, [{{:., _, [receiver, name]}, _, []}, arity]}]} = node, acc)
       when name in @entry_names and is_integer(arity) do
    {node, entry_arity(acc, receiver(receiver, acc), name, arity, meta)}
  end

  defp pre({:apply, meta, [module, name, args]} = node, acc) when name in @entry_names do
    {node, entry(acc, receiver(module, acc), name, args, meta)}
  end

  defp pre(
         {{:., _, [{:__aliases__, _, [:Kernel]}, :apply]}, meta, [module, name, args]} = node,
         acc
       )
       when name in @entry_names do
    {node, entry(acc, receiver(module, acc), name, args, meta)}
  end

  defp pre(node, acc), do: {node, acc}

  # A literal argument list must have two elements; a computed one is
  # flagged, since its arity can't be seen.
  defp two_args?(args) when is_list(args), do: length(args) == 2
  defp two_args?(_computed), do: true

  defp post({:defmodule, _, _} = node, acc), do: {node, pop(acc, :module)}

  defp post({kind, _, [{name, _, _} | _]} = node, acc)
       when kind in [:def, :defp] and is_atom(name),
       do: {node, pop(acc, :function)}

  defp post(node, acc), do: {node, acc}

  defp pop(%{stack: [{kind, _, aliases} | rest]} = acc, kind),
    do: %{acc | stack: rest, aliases: aliases}

  defp pop(acc, _kind), do: acc

  defp current(acc, kind) do
    Enum.find_value(acc.stack, fn
      {^kind, value, _aliases} -> value
      _ -> nil
    end)
  end

  defp receiver({:__aliases__, _, [first | rest]}, acc) do
    case Map.fetch(acc.aliases, first) do
      {:ok, target} -> Module.concat([target | rest])
      :error -> Module.concat([first | rest])
    end
  end

  defp receiver({:__MODULE__, _, _}, acc), do: current(acc, :module)
  defp receiver(atom, _acc) when is_atom(atom), do: atom
  defp receiver(_other, _acc), do: :dynamic

  # A known module is flagged only if it implements the behaviour; a
  # dynamic receiver is always flagged. A provider calling its own module
  # is exempt.
  defp record(acc, receiver, name, meta) do
    module = current(acc, :module)

    cond do
      receiver == :dynamic -> add(acc, :calls, receiver, name, meta)
      receiver == module -> acc
      provider?(receiver) -> add(acc, :calls, receiver, name, meta)
      true -> acc
    end
  end

  # `call` on a server (or a dynamic receiver) is the server message when
  # its message is `{:complete, _, _}` or its argument list is computed;
  # otherwise every name is checked against the entry points' arities.
  defp entry(acc, receiver, :call, args, meta)
       when receiver in @servers or receiver == :dynamic do
    cond do
      server_message?(args) -> add(acc, :entries, receiver, @server_message, meta)
      receiver == :dynamic -> entry_arity(acc, receiver, :call, length(args), meta)
      true -> acc
    end
  end

  defp entry(acc, receiver, name, args, meta),
    do: entry_arity(acc, receiver, name, if(is_list(args), do: length(args), else: :any), meta)

  defp server_message?([_server, {:{}, _, [:complete, _request, _enqueued_at]} | rest]),
    do: length(rest) <= 1

  defp server_message?(args) when is_list(args), do: false
  defp server_message?(_computed), do: true

  # A known receiver is flagged when it is that entry point at that arity; a
  # dynamic one when any entry point has that name and arity.
  defp entry_arity(acc, receiver, name, arity, meta) do
    entry_point? =
      Enum.any?(@entry_points, fn {{module, entry_name}, entry_arity} ->
        entry_name == name and receiver in [module, :dynamic] and arity in [entry_arity, :any]
      end)

    if entry_point?, do: add(acc, :entries, receiver, name, meta), else: acc
  end

  defp add(acc, field, receiver, name, meta) do
    call = %{
      key: {current(acc, :module), current(acc, :function), receiver, name},
      line: meta[:line]
    }

    Map.update!(acc, field, &[call | &1])
  end

  defp provider?(module) do
    Code.ensure_loaded?(module) and
      @behaviour_module in List.flatten(
        Keyword.get_values(module.module_info(:attributes), :behaviour)
      )
  end
end

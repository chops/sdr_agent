defmodule SdrAgentWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :sdr_agent

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_sdr_agent_key",
    signing_salt: "FJVbw75m",
    same_site: "Lax"
  ]

  # Test builds read the session options at runtime (`session_options/0`),
  # so the R0-07 calibration console, when active, uses its own cookie name
  # for HTTP and the LiveView socket alike. Other builds are unchanged.
  if Mix.env() == :test do
    @console_session_options Keyword.put(
                               @session_options,
                               :key,
                               SdrAgentWeb.CalibrationConsole.session_key()
                             )

    @doc "The session options in effect (the calibration console's own when it is active)."
    def session_options do
      if SdrAgentWeb.CalibrationConsole.active?(),
        do: @console_session_options,
        else: @session_options
    end

    socket "/live", Phoenix.LiveView.Socket,
      websocket: [connect_info: [session: {__MODULE__, :session_options, []}]],
      longpoll: [connect_info: [session: {__MODULE__, :session_options, []}]]
  else
    @doc "The session options in effect."
    def session_options, do: @session_options

    socket "/live", Phoenix.LiveView.Socket,
      websocket: [connect_info: [session: @session_options]],
      longpoll: [connect_info: [session: @session_options]]
  end

  # First: tag credential-bearing requests (auth, magic-link, sign-in and
  # sign-out paths, classified as the router decodes them) before anything
  # parses, routes or reports them, so their error reports are withheld
  # through the outer HTTP error boundary (`SdrAgentWeb.SensitiveAuth`).
  plug SdrAgentWeb.SensitiveAuth

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :sdr_agent,
    gzip: not code_reloading?,
    only: SdrAgentWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  if Mix.env() == :dev do
    plug Tidewave
  end

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :sdr_agent
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  # The request line is logged at :info except for magic-link confirmation
  # paths in any spelling the router routes (Codex M2, P1), whose last
  # segment is a live sign-in token: those are never logged by the endpoint
  # (`log_level/1`), and the router and LiveView logs filter the `token`
  # and `magic_link` params (config :phoenix, :filter_parameters).
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  # S13 browser smoke attestation: test config only (see the module).
  if Application.compile_env(:sdr_agent, :smoke_attestation_plug, false) do
    plug SdrAgentWeb.SmokeAttestation
  end

  # R0-07 calibration console page allowlist: test builds only, inert unless
  # `mix sdr.calibration.console serve` activated it (see the module).
  if Mix.env() == :test do
    plug SdrAgentWeb.CalibrationConsole
  end

  # S9: webhook requests are read raw (bounded) before any parsing.
  plug SdrAgentWeb.WebhookIntake

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head

  if Mix.env() == :test do
    plug :session
  else
    plug Plug.Session, @session_options
  end

  plug SdrAgentWeb.Router

  @doc """
  The endpoint request-line log level (`Plug.Telemetry`'s `:log`): `false`
  for a magic-link confirmation path in any spelling the router routes
  there (`SdrAgentWeb.SensitiveAuth.token_path?/1`: the URI-decoded first
  segment, as `Phoenix.Router` decodes before matching), else `:info`. The
  request is classified, never altered.
  """
  def log_level(conn), do: if(SdrAgentWeb.SensitiveAuth.token_path?(conn), do: false, else: :info)

  if Mix.env() == :test do
    @session_init Plug.Session.init(@session_options)
    @console_session_init Plug.Session.init(@console_session_options)

    defp session(conn, _opts) do
      init =
        if SdrAgentWeb.CalibrationConsole.active?(),
          do: @console_session_init,
          else: @session_init

      Plug.Session.call(conn, init)
    end
  end
end
